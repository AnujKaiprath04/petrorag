def generate_table4_latency_tokens(baselines: List[Dict[str, Any]]) -> str:
    """Generates Table 4: Latency Decomposition and Token Budget Economics."""
    lines = [
        r"% Auto-generated by experiments/eval/latex_generator.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\caption{Computational Latency and Token Footprint Across Evaluated Architectures.}",
        r"\label{tab:latency_tokens}",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"\textbf{Model Architecture} & \textbf{Prompt Tok.} & \textbf{Compl. Tok.} & \textbf{Total Tok.} & \textbf{Mean Latency} \\",
        r"\midrule"
    ]

    for b in baselines:
        name = b["model_name"]
        ptok = f"{b['mean_prompt_tokens']:.1f}"
        ctok = f"{b['mean_completion_tokens']:.1f}"
        ttok = f"{b['mean_total_tokens']:.1f}"
        lat = f"{b['mean_latency_ms']:.1f} ms"
        lines.append(f"{name} & {ptok} & {ctok} & {ttok} & {lat} \\\\")

    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}"
    ])
    return "\n".join(lines) + "\n"


def build_all_latex_tables():
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    baselines_path = RESULTS_DIR / "baseline_comparison_results.json"
    ablations_path = RESULTS_DIR / "ablation_study_results.json"

    baselines = load_json(baselines_path)
    ablations = load_json(ablations_path)

    # Table 1: Baselines
    t1_content = generate_table1_baselines(baselines)
    t1_path = TABLES_DIR / "table1_baseline_comparison.tex"
    with open(t1_path, "w", encoding="utf-8") as f:
        f.write(t1_content)
    print(f"[OK] Generated {t1_path}")

    # Table 2: Ablations
    t2_content = generate_table2_ablations(ablations)
    t2_path = TABLES_DIR / "table2_ablation_study.tex"
    with open(t2_path, "w", encoding="utf-8") as f:
        f.write(t2_content)
    print(f"[OK] Generated {t2_path}")

    # Table 3: Safety Guardrails
    t3_content = generate_table3_safety()
    t3_path = TABLES_DIR / "table3_abstention_safety.tex"
    with open(t3_path, "w", encoding="utf-8") as f:
        f.write(t3_content)
    print(f"[OK] Generated {t3_path}")

    # Table 4: Latency & Tokens
    t4_content = generate_table4_latency_tokens(baselines)
    t4_path = TABLES_DIR / "table4_latency_tokens.tex"
    with open(t4_path, "w", encoding="utf-8") as f:
        f.write(t4_content)
    print(f"[OK] Generated {t4_path}")


if __name__ == "__main__":
    build_all_latex_tables()
